    def normalize(self, text: str):
        text = text.lower()
        text = re.sub(r"[^\w\s]", " ", text)

        return {
            w.strip()
            for w in text.split()
            if len(w.strip()) > 1
            and w.strip() not in self.STOP_WORDS
        }

    def is_book_wide_query(self, question: str) -> bool:
        question_lower = question.lower()

        if any(
            q in question_lower
            for q in self.BOOK_SUMMARY_QUERIES
        ):
            return True

        # طلب نطاق صفحات كبير
        numbers = [
            int(x)
            for x in re.findall(r"\d+", question_lower)
        ]

        if len(numbers) >= 2:
            if max(numbers) - min(numbers) >= 20:
                return True

        return False

    def search(
        self,
        question: str,
        chunks: List[str],
        top_k: int = 5,
    ) -> List[str]:

        if not chunks:
            return []

        # --------------------------------------------------
        # أسئلة الكتاب بالكامل
        # --------------------------------------------------
        if self.is_book_wide_query(question):

            print(
                f"📚 BOOK-WIDE SEARCH: returning "
                f"{len(chunks)} chunks"
            )

            return chunks

        # --------------------------------------------------
        # سؤال محدد
        # --------------------------------------------------
        question_words = self.normalize(question)

        scored = []

        for chunk in chunks:

            chunk_words = self.normalize(chunk)

            score = 0

            for word in question_words:

                if word in chunk_words:
                    score += 2

                else:
                    for chunk_word in chunk_words:
                        if (
                            len(word) > 3
                            and len(chunk_word) > 3
                            and word[:4] == chunk_word[:4]
                        ):
                            score += 1
                            break

            if score > 0:
                scored.append((score, chunk))

        scored.sort(
            key=lambda x: x[0],
            reverse=True
        )

        if not scored:
            return []

        return [
            chunk
            for score, chunk in scored[:top_k]
        ]
