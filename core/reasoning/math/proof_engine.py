class ProofEngine:


    def prove(self, question):

        text = str(question).lower()


        if (
            "فيثاغورس" in text
            or
            "pythagoras" in text
        ):

            return {

                "theorem": "نظرية فيثاغورس",

                "steps": [

                    "نفرض مثلثاً قائماً ABC",

                    "نحدد الوتر c المقابل للزاوية القائمة",

                    "نطبق العلاقة a^2 + b^2 = c^2",

                    "نستنتج أن مربع الوتر يساوي مجموع مربعي الضلعين القائمين"

                ]

            }



        if "زوايا المثلث" in text:

            return {

                "theorem": "مجموع زوايا المثلث",

                "steps": [

                    "نرسم خطاً موازياً لأحد أضلاع المثلث",

                    "نستخدم الزوايا المتبادلة",

                    "نثبت أن مجموع الزوايا الداخلية يساوي 180 درجة"

                ]

            }



        return {

            "theorem": "غير معروف",

            "steps": [

                "لم يتم العثور على برهان مخزن"

            ]

        }
