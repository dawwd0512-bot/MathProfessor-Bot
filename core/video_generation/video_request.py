from core.ai.gemini import ask_gemini


def build_video_plan(user_request: str):
    prompt = f"""
أنت مخرج ومخطط فيديوهات بالذكاء الاصطناعي.

حوّل طلب المستخدم التالي إلى خطة فيديو واضحة وقابلة للتنفيذ.

مهم جدًا:
- لا تفترض أن الفيديو تعليمي.
- يمكن أن يكون تعليميًا، ترفيهيًا، إعلانيًا، قصصيًا، وثائقيًا،
  إخباريًا، سينمائيًا، لمنصات التواصل، أو أي نوع آخر.
- إذا ذكر المستخدم أسلوبًا أو شخصية أو لهجة أو مدة، احترمها.
- إذا لم يحدد المستخدم بعض التفاصيل، اختر افتراضات مناسبة.
- لا تغيّر فكرة المستخدم الأساسية.

أرجع النتيجة بهذا الشكل فقط:

TYPE:
نوع الفيديو

TITLE:
عنوان مناسب

LANGUAGE:
لغة الفيديو

STYLE:
الأسلوب البصري

TONE:
نبرة الفيديو

DURATION:
المدة التقريبية

CHARACTER:
وصف الشخصية أو المتحدث، إن وجد

VOICE:
وصف الصوت

SCENES:
1. وصف المشهد الأول
2. وصف المشهد الثاني
3. وصف المشهد الثالث
4. أكمل حسب الحاجة

NARRATION:
النص الكامل الذي سيتم تحويله إلى صوت

VISUALS:
وصف العناصر البصرية المطلوبة في الفيديو

USER REQUEST:
{user_request}
"""

    result = ask_gemini(
        prompt,
        [],
        []
    )

    if not result:
        raise RuntimeError(
            "لم يتم إنشاء خطة الفيديو."
        )

    return result
